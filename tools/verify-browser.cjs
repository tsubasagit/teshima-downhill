  await page.screenshot({path:path.join(out,'title.jpg'),quality:65});
  await page.locator('#startBtn').click();
  await page.waitForTimeout(900);
  await page.keyboard.down('ArrowRight');
  assert.equal(await page.evaluate(()=>input.steer),1);
  assert.ok(await page.evaluate(()=>Math.abs(state.visualSteer)<1),'pose does not snap to full lean');
  await page.waitForTimeout(350);await page.keyboard.up('ArrowRight');
  assert.ok(await page.evaluate(()=>state.xOffset>0));assert.equal(await page.evaluate(()=>input.steer),0);
  await page.keyboard.down('ArrowDown');await page.waitForTimeout(1000);await page.keyboard.up('ArrowDown');
  assert.ok(await page.evaluate(()=>state.currentSpeed<CONFIG.speed*0.6),'brake reduces speed');
  await page.keyboard.press('Space');assert.equal(await page.evaluate(()=>state.paused),true);
  const pausedDistance=await page.evaluate(()=>state.distance);await page.waitForTimeout(200);
  assert.equal(await page.evaluate(()=>state.distance),pausedDistance);
  await page.locator('#resumeBtn').click();assert.equal(await page.evaluate(()=>state.paused),false);
  await page.locator('#labBtn').click();assert.equal(await page.evaluate(()=>state.paused),true);
  await page.locator('#speedSlider').fill('54');assert.equal(await page.evaluate(()=>CONFIG.speed),54);
  assert.match(await page.locator('#labCode').textContent(),/speed: 54/);
  await page.locator('#steerSlider').focus();await page.keyboard.press('ArrowRight');
  assert.equal(await page.evaluate(()=>input.steer),0,'range arrows do not steer');
  await page.screenshot({path:path.join(out,'lab.jpg'),quality:65});
  await page.locator('#labReset').click();assert.equal(await page.evaluate(()=>CONFIG.speed),36);
  await page.locator('#labClose').click();assert.equal(await page.evaluate(()=>state.paused),false);
  await page.keyboard.press('Space');assert.equal(await page.evaluate(()=>state.paused),true);
  // Open the lab from a paused state using its underlying handler; preserve that state.
  await page.evaluate(()=>document.getElementById('labBtn').click());
  await page.locator('#labClose').click();assert.equal(await page.evaluate(()=>state.paused),true);
  await page.locator('#resumeBtn').click();
  await page.mouse.move(300,350);await page.mouse.down();assert.ok(await page.evaluate(()=>input.steer<0));
  await page.mouse.move(900,350);assert.ok(await page.evaluate(()=>input.steer>0));
  await page.mouse.move(550,350);assert.equal(await page.evaluate(()=>input.steer),0);
  await page.mouse.up();assert.equal(await page.evaluate(()=>canvasPointer),null);
  await page.keyboard.down('ArrowLeft');await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  assert.equal(await page.evaluate(()=>state.paused),true);assert.equal(await page.evaluate(()=>input.steer),0);
  await page.keyboard.up('ArrowLeft');await page.locator('#resumeBtn').click();
  await page.evaluate(()=>{resetRun();state.running=true;});await page.waitForTimeout(1500);
  await page.evaluate(()=>state.paused=true);await page.screenshot({path:path.join(out,'coastal-ride.jpg'),quality:75});
  // Inspect later scenery after camera settles, without waiting for a complete lap.
  await page.evaluate(()=>{state.distance=205;state.paused=false});await page.waitForTimeout(1700);
  await page.evaluate(()=>state.paused=true);await page.screenshot({path:path.join(out,'curve.jpg'),quality:65});
  await page.evaluate(()=>{state.distance=state.totalLength-110;state.paused=false});await page.waitForTimeout(1500);
  await page.evaluate(()=>state.paused=true);await page.screenshot({path:path.join(out,'harbor.jpg'),quality:65});
