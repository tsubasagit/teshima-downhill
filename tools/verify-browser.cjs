  assert.equal(await phone.evaluate(()=>input.steer),-1);assert.equal(await phone.evaluate(()=>input.brake),true);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[{...left,id:1}]});
  assert.equal(await phone.evaluate(()=>input.steer),0);assert.equal(await phone.evaluate(()=>input.brake),true);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
